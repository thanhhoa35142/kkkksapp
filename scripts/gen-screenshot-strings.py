#!/usr/bin/env python3
"""Writes MyAppUITests/ScreenshotStrings.swift: the translations of the
labels the screenshot tests tap, taken from Shared/Localizable.xcstrings.

The UI test runner can't read the app's string catalog, so the labels it
needs are copied here. Run again after changing one of these strings or
adding a label to KEYS.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LANGS = ("nl", "de", "es")
KEYS = [
    "Choose a City", "Choose a City…", "Choose a Time…", "Continue",
    "Delete My Data", "Filters", "Is this spot still here?", "Map",
    "Next 7 days", "Next good time", "Saved", "See more picks with Plus", "Settings",
    "Where's Nice This Weekend?", "Why %lld?",
]
# Drawn by UIKit (the iPad tab bar's overflow button), not in the catalog.
SYSTEM = {"More": {"nl": "Meer", "de": "Mehr", "es": "Más"}}


def swift(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


catalog = json.loads((ROOT / "Shared/Localizable.xcstrings").read_text())["strings"]
table = dict(SYSTEM)
for key in KEYS:
    locs = catalog[key]["localizations"]
    table[key] = {l: locs[l]["stringUnit"]["value"] for l in LANGS}

lines = [
    "// Generated by scripts/gen-screenshot-strings.py from",
    "// Shared/Localizable.xcstrings. Do not edit by hand.",
    "",
    "enum ScreenshotStrings {",
    "    static let table: [String: [String: String]] = [",
]
for key in sorted(table):
    pairs = ", ".join(f"{swift(l)}: {swift(v)}" for l, v in sorted(table[key].items()))
    lines.append(f"        {swift(key)}: [{pairs}],")
lines += ["    ]", "}", ""]
(ROOT / "MyAppUITests/ScreenshotStrings.swift").write_text("\n".join(lines))
